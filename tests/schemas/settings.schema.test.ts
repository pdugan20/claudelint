describe('MarketplaceConfigSchema', () => {
  it('models autoUpdate, the documented entry toggle', () => {
    // "Each marketplace entry also accepts an optional `autoUpdate` Boolean... official
    // Anthropic marketplaces default to `true` and all other marketplaces default to
    // `false`" (docs-baseline/settings.md:821).
    const result = MarketplaceConfigSchema.safeParse({
      source: { source: 'github', repo: 'acme/plugins' },
      autoUpdate: true,
    });
    expect(result.success).toBe(true);
  });

  it('does not model the invented `enabled` toggle', () => {
    // `enabled` appears nowhere on a marketplace entry. The schema is non-strict, so the
    // parse succeeds -- what matters is that the key is STRIPPED, not modelled, so
    // claudelint never blesses a toggle Claude Code ignores.
    const result = MarketplaceConfigSchema.parse({
      source: { source: 'github', repo: 'acme/plugins' },
      enabled: true,
    });

    expect(result).not.toHaveProperty('enabled');
  });

  it('accepts skipLfs on a git-backed source', () => {
    const result = MarketplaceConfigSchema.safeParse({
      source: { source: 'github', repo: 'acme/plugins', skipLfs: true },
    });
    expect(result.success).toBe(true);
  });
});

describe('SettingsSchema — the documented surface', () => {
  it('accepts the documented statusLine object', () => {
    // Was `z.string()`, so the docs' own example was rejected: "expected string, received
    // object". Found by the type-conformance gate the moment `Available settings` was bound.
    const result = SettingsSchema.safeParse({
      statusLine: { type: 'command', command: '~/.claude/statusline.sh' },
    });
    expect(result.success).toBe(true);
  });

  it('accepts the documented teammateMode string', () => {
    // Was `z.boolean()`, so `"auto"` -- the documented example -- was rejected.
    expect(SettingsSchema.safeParse({ teammateMode: 'auto' }).success).toBe(true);
  });

  it('models the documented settings surface, not 23 of 117 keys', () => {
    // 94 documented keys were stripped silently by this non-strict object: a user writing
    // them got no validation, and a typo got no warning.
    const modeled = Object.keys(SettingsSchema.shape);

    expect(modeled.length).toBeGreaterThanOrEqual(110);
    for (const field of ['autoCompactEnabled', 'availableModels', 'agent', 'viewMode', 'voice']) {
      expect(modeled).toContain(field);
    }
  });

  it('accepts every documented strictKnownMarketplaces source type', () => {
    // docs-baseline/settings.md:872 — "The allowlist supports multiple marketplace source
    // types. Most sources use exact matching, while `hostPattern` and `pathPattern` use
    // regex matching against the marketplace host and filesystem path respectively."
    //
    // `pathPattern` was missing from the enum, so the documented example at
    // settings.md:955 — { "source": "pathPattern", "pathPattern": "^/opt/approved/" } —
    // was rejected with "Invalid option".
    const documentedSources = [
      { source: 'github', repo: 'owner/repo' },
      { source: 'git', url: 'https://example.com/x.git' },
      { source: 'url', url: 'https://example.com/m.json' },
      { source: 'npm', package: '@scope/pkg' },
      { source: 'directory', path: '/opt/approved' },
      { source: 'file', path: '/opt/approved/m.json' },
      { source: 'hostPattern', hostPattern: '^github\\.com$' },
      { source: 'pathPattern', pathPattern: '^/opt/approved/' },
    ];

    for (const entry of documentedSources) {
      const result = SettingsSchema.safeParse({ strictKnownMarketplaces: [entry] });
      expect(result.success).toBe(true);
    }
  });

  it('does NOT model the global config keys, which belong in ~/.claude.json', () => {
    // "These settings are stored in `~/.claude.json` rather than `settings.json`. Adding
    // them to `settings.json` will trigger a schema validation error." Modelling them here
    // would assert the opposite of what upstream says.
    const modeled = Object.keys(SettingsSchema.shape);

    for (const globalOnly of ['autoUpdates', 'hasCompletedOnboarding']) {
      expect(modeled).not.toContain(globalOnly);
    }
  });
});
