describe('SettingsSchema', () => {
  describe('valid configurations', () => {
    it('should accept empty settings object', () => {
      const result = SettingsSchema.safeParse({});
      expect(result.success).toBe(true);
    });

    it('should accept settings with all fields', () => {
      const result = SettingsSchema.safeParse({
        $schema: 'https://json.schemastore.org/claude-code-settings.json',
        permissions: {
          allow: ['Read'],
          deny: ['Bash(rm *)'],
          ask: ['Write'],
        },
        env: {
          NODE_ENV: 'development',
        },
        model: 'sonnet',
        apiKeyHelper: 'get-api-key.sh',
        hooks: {},
        attribution: {
          commit: 'Generated by Claude',
          pr: 'Created with Claude Code',
        },
        // An OBJECT, not a string (docs-baseline/settings.md:300). This test asserted the
        // string form, which is how the false positive stayed shipped.
        statusLine: { type: 'command', command: '~/.claude/statusline.sh' },
        outputStyle: 'concise',
        sandbox: {
          enabled: true,
        },
        enabledPlugins: {
          'my-plugin': true,
        },
        autoUpdatesChannel: 'stable',
        cleanupPeriodDays: 30,
        language: 'en',
        respectGitignore: true,
        enableAllProjectMcpServers: false,
        disableAllHooks: false,
        // A STRING enum (`in-process`, `auto`, ...), not a boolean (settings.md:304).
        teammateMode: 'auto',
        showTurnDuration: true,
        terminalProgressBarEnabled: true,
        spinnerTipsEnabled: true,
        alwaysThinkingEnabled: false,
        prefersReducedMotion: false,
        plansDirectory: '.claude/plans',
        skipWebFetchPreflight: false,
      });
      expect(result.success).toBe(true);
    });
  });

  describe('model field', () => {
    it('should accept any string for model', () => {
      const result = SettingsSchema.safeParse({
        model: 'sonnet',
      });
      expect(result.success).toBe(true);
    });

    it('should accept model aliases', () => {
      const result = SettingsSchema.safeParse({
        model: 'claude-sonnet-4-5-20250929',
      });
      expect(result.success).toBe(true);
    });

    it('should accept custom model names', () => {
      const result = SettingsSchema.safeParse({
        model: 'my-custom-model',
      });
      expect(result.success).toBe(true);
    });
  });

  describe('env field', () => {
    it('should accept env variables object', () => {
      const result = SettingsSchema.safeParse({
        env: {
          API_KEY: 'secret',
          DEBUG: 'true',
        },
      });
      expect(result.success).toBe(true);
    });

    it('should accept empty env object', () => {
      const result = SettingsSchema.safeParse({
        env: {},
      });
      expect(result.success).toBe(true);
    });
  });

  describe('enabledPlugins field', () => {
    it('should accept plugin enable/disable map', () => {
      const result = SettingsSchema.safeParse({
        enabledPlugins: {
          'plugin-a': true,
          'plugin-b': false,
          'plugin-c': true,
        },
      });
      expect(result.success).toBe(true);
    });
  });
});

